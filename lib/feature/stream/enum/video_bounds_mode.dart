/// 下发给设备的**画质档位**（决定 `CHANGE_STREAM_PARAMETERS` 里的 `bounds`）。
///
/// 背景：`bounds` 是"请设备按这个框出图"的意思，而同一个 1280x720 的设备画面
/// 编成多少像素，直接决定客户端那边清不清晰：
///
/// - 编得少（例如 992x560）→ 本地要放大 2 倍以上，肉眼就是糊；
/// - 编得多（例如 2560x1440）→ 本地几乎不放大、甚至下采样，清晰，但**设备侧要真编
///   这么多像素**（redroid 容器里的软编码器压力大，实测过帧间隔被拖到 53–166ms，
///   见 AGENTS §12.7）。
///
/// 服务端自带的网页端走的是"要得多"那一路：它把**浏览器视口尺寸**当 `bounds` 发过去
/// （`getMaxSize()` 取 `document.body.clientWidth/clientHeight` 并对齐 16，
/// 既不乘 DPR、也不按设备原生封顶）——这就是"网页端看着更清楚"的机制。
///
/// ## 为什么是**三档**而不是一个"清晰优先"开关（2026-10-07 用户反馈）
///
/// 原来只有"省设备算力（=原生）"与"清晰优先（=视口，上限原生×2）"两档，
/// 用户实测"**那个清晰优先并不能切换画质**"。原因是两档在**不少设备上会算出同一个边界**：
/// 手机上画面区的物理像素往往就在原生附近，而"省设备算力"那档还带一条
/// "贴到原生 90% 就直接要原生"的吸附（[snapToNativeRatio]），于是两档都是 1280x720。
///
/// 现在按**"最多允许设备编到原生的几倍"**分档，相邻两档至少差 50% 像素量，
/// 在任何设备上都能看出区别；并且"更多"面板里直接显示**生效编码边界 + 本地放大倍率**，
/// 切了有没有生效一眼可查（不再靠肉眼猜）。
enum VideoBoundsMode {
  /// 流畅运行：编码边界**不超过设备原生**。
  ///
  /// 设备侧最省力（软编码器压力最小 → 帧率/延迟最好），代价是客户端画面区比原生大时
  /// 要靠本地放大，会偏糊。带"贴原生就吸原生"的吸附（转屏不会反复重建编码器）。
  smooth(
    '流畅运行',
    1.0,
    '设备只编原生分辨率，最省算力、最顺；画面靠本地放大，可能偏糊',
  ),

  /// 推荐（默认）：上限 = 原生 × 1.5。
  balanced('推荐', 1.5, '最多编到原生 1.5 倍像素：明显比"原生"清晰，设备还扛得住'),

  /// 最高画质：上限 = 原生 × 2（也就是 2026-10-07 那版"清晰优先"的行为）。
  maximum('最高画质', 2.0, '最多编到原生 2 倍像素：最清晰，设备编码压力最大，可能掉帧');

  const VideoBoundsMode(this.label, this.upscaleCap, this.description);

  /// UI 用的中文名。
  final String label;

  /// 该档允许的**上限**：设备原生分辨率的倍数。
  ///
  /// 注意它是"上限"不是"目标值"——实际要多少还得看客户端画面区的物理像素
  /// （见 `clampBoundsForMode`：先按设备比例内接于视口，再按这个上限封顶）。
  /// 取 1.0 表示"不许超过原生"。
  final double upscaleCap;

  /// UI 用的说明（代价是什么）。
  final String description;

  /// "吸附到原生"的门槛：视口按设备比例收框后的宽度达到原生的这个比例时，
  /// 干脆要原生（换来"转屏不改边界、不发消息、画面不断"，详见 `clampBoundsForMode`）。
  ///
  /// 只对 [smooth] 生效：其它档本来就要更多像素，吸附过去等于把档位吃掉了。
  static const double snapToNativeRatio = 0.9;

  /// 是否允许"贴原生就吸原生"（只有 [smooth] 需要，见 [snapToNativeRatio]）。
  bool get snapsToNative => upscaleCap <= 1.0;

  /// 日志/面板里的上限说法（例如 `原生`、`原生 ×1.5`、`原生 ×2`）。
  String get upscaleLabel => upscaleCap <= 1.0
      ? '原生'
      : '原生 ×${upscaleCap == upscaleCap.roundToDouble() ? upscaleCap.toStringAsFixed(0) : upscaleCap.toStringAsFixed(1)}';
}
